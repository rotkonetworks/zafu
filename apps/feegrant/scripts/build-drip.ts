// Compiles contracts/Drip.sol into src/drip-artifact.ts.
// Settings are fixed so the bytecode is reproducible; `--check` compares only.
import { readFileSync, writeFileSync } from 'node:fs';
import solc from 'solc';

const SOURCE = new URL('../contracts/Drip.sol', import.meta.url);
const OUT = new URL('../src/drip-artifact.ts', import.meta.url);

export const compileDrip = (): { abi: unknown[]; bytecode: string } => {
  const input = {
    language: 'Solidity',
    sources: { 'Drip.sol': { content: readFileSync(SOURCE, 'utf8') } },
    settings: {
      optimizer: { enabled: true, runs: 200 },
      evmVersion: 'paris',
      outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object'] } },
    },
  };
  const out = JSON.parse(solc.compile(JSON.stringify(input))) as {
    errors?: { severity: string; formattedMessage: string }[];
    contracts: { 'Drip.sol': { Drip: { abi: unknown[]; evm: { bytecode: { object: string } } } } };
  };
  const errors = (out.errors ?? []).filter(e => e.severity === 'error');
  if (errors.length) {
    throw new Error(errors.map(e => e.formattedMessage).join('\n'));
  }
  const c = out.contracts['Drip.sol'].Drip;
  return { abi: c.abi, bytecode: `0x${c.evm.bytecode.object}` };
};

export const renderArtifact = (): string => {
  const { abi, bytecode } = compileDrip();
  return (
    `// Generated by scripts/build-drip.ts from contracts/Drip.sol - do not edit.\n` +
    `export const DRIP_ABI = ${JSON.stringify(abi)} as const;\n\n` +
    `export const DRIP_BYTECODE = '${bytecode}' as const;\n`
  );
};

if (import.meta.main) {
  const next = renderArtifact();
  if (process.argv[2] === '--check') {
    const same = readFileSync(OUT, 'utf8').trim() === next.trim();
    console.log(same ? 'drip-artifact.ts is up to date' : 'drip-artifact.ts is STALE');
    process.exit(same ? 0 : 1);
  }
  writeFileSync(OUT, next);
  console.log('wrote src/drip-artifact.ts');
}
